// Regenerates THIRD-PARTY-LICENSES.txt — the full license/notice texts for
// everything compiled into the distributed app (frontend bundle + Rust binary
// + vendored fonts). Run after dependency changes: `npm run licenses`.
//
// The file ships inside the app (imported ?raw by the About screen), which is
// what makes the MIT/ISC/Apache notice conditions hold for setup.exe.

import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

// Everything Vite puts in the production frontend bundle. lucide-static is a
// devDependency but its SVGs are copied into dist, so it belongs here.
const NPM_BUNDLED = [
  'react',
  'react-dom',
  'scheduler',
  'js-tokens',
  'loose-envify',
  '@tauri-apps/api',
  '@tauri-apps/plugin-dialog',
  '@tauri-apps/plugin-sql',
  'lucide-static',
];

const LICENSE_FILE = /^(licen[cs]e|copying|notice)([-_.].*)?$/i;

function licenseFilesIn(dir) {
  let names;
  try {
    names = readdirSync(dir, { withFileTypes: true });
  } catch {
    return [];
  }
  return names
    .filter((e) => e.isFile() && LICENSE_FILE.test(e.name) && !e.name.endsWith('.spdx'))
    .map((e) => join(dir, e.name));
}

// Pool of unique license texts; each entry lists who it covers, so the
// boilerplate Apache-2.0 body prints once instead of two hundred times.
const pool = new Map(); // hash -> { text, users: [] }
const noText = new Map(); // spdx expr -> [users]

function addUser(user, dir, spdx) {
  const files = licenseFilesIn(dir);
  if (files.length === 0) {
    const key = spdx || 'unknown';
    if (!noText.has(key)) noText.set(key, []);
    noText.get(key).push(user);
    return;
  }
  for (const f of files) {
    const text = readFileSync(f, 'utf8').replace(/\r\n/g, '\n').trim();
    if (text.length === 0 || text.length > 200_000) continue;
    const hash = createHash('sha256').update(text).digest('hex');
    if (!pool.has(hash)) pool.set(hash, { text, users: [] });
    pool.get(hash).users.push(user);
  }
}

// --- npm ---
for (const pkg of NPM_BUNDLED) {
  const dir = join(root, 'node_modules', pkg);
  const meta = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
  addUser(`${pkg}@${meta.version} (${meta.license ?? '?'})`, dir, meta.license);
}

// --- cargo ---
const cargoManifest = join(root, 'src-tauri', 'Cargo.toml');
const tree = execFileSync(
  'cargo',
  ['tree', '-e', 'normal', '--prefix', 'none', '--format', '{p}', '--manifest-path', cargoManifest],
  { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 },
);
const linked = new Set();
for (const line of tree.split('\n')) {
  const m = line.trim().match(/^(\S+) v(\S+)/);
  if (m && m[1] !== 'stillsong') linked.add(`${m[1]} ${m[2]}`);
}
const metadata = JSON.parse(
  execFileSync('cargo', ['metadata', '--format-version', '1', '--manifest-path', cargoManifest], {
    encoding: 'utf8',
    maxBuffer: 256 * 1024 * 1024,
  }),
);
for (const p of metadata.packages) {
  if (!linked.has(`${p.name} ${p.version}`)) continue;
  addUser(`${p.name}@${p.version} (${p.license ?? '?'})`, dirname(p.manifest_path), p.license);
}

// --- vendored fonts ---
for (const f of ['OFL-Newsreader.txt', 'OFL-SourceSans3.txt', 'OFL-IBMPlexMono.txt']) {
  const path = join(root, 'src', 'ui', 'fonts', f);
  if (!existsSync(path)) throw new Error(`missing font license: ${f}`);
  const text = readFileSync(path, 'utf8').replace(/\r\n/g, '\n').trim();
  const hash = createHash('sha256').update(text).digest('hex');
  if (!pool.has(hash)) pool.set(hash, { text, users: [] });
  pool.get(hash).users.push(`${f.replace(/^OFL-|\.txt$/g, '')} font (OFL-1.1)`);
}

// --- emit ---
const RULE = '='.repeat(72);
const parts = [
  `Third-party license notices for Stillsong
Stillsong itself is GPL-3.0 (see LICENSE). This file reproduces the license
and notice texts of the open-source components compiled into the distributed
application: the frontend packages bundled by Vite, every Rust crate linked
into the binary, and the vendored fonts. Components downloaded at first run
(ComfyUI, llama.cpp, Python, model weights) are governed by their own
licenses — see THIRD-PARTY-NOTICES.md.

All Rust crates are used unmodified; the source code of every crate listed
here is available at https://crates.io/ under the crate's name and version.
The npm packages' source is available at https://www.npmjs.com/ likewise.

Generated by scripts/generate-third-party-licenses.mjs — do not edit by hand.`,
];

const entries = [...pool.values()].sort((a, b) => a.users[0].localeCompare(b.users[0]));
for (const { text, users } of entries) {
  parts.push(`${RULE}\nThis license text applies to:\n${[...new Set(users)].map((u) => `  - ${u}`).join('\n')}\n${RULE}\n\n${text}`);
}
if (noText.size > 0) {
  const lines = [...noText.entries()]
    .sort()
    .map(([spdx, users]) => `${spdx}:\n${[...new Set(users)].map((u) => `  - ${u}`).join('\n')}`);
  parts.push(`${RULE}\nThe following crates declare a license but publish no license text file in
the crate itself. Their license terms are the standard texts identified by
the SPDX expressions below (https://spdx.org/licenses/); the corresponding
generic bodies are reproduced elsewhere in this file.\n${RULE}\n\n${lines.join('\n\n')}`);
}

writeFileSync(join(root, 'THIRD-PARTY-LICENSES.txt'), parts.join('\n\n') + '\n');
console.log(
  `THIRD-PARTY-LICENSES.txt: ${entries.length} unique license texts, ` +
    `${linked.size} crates + ${NPM_BUNDLED.length} npm packages + 3 fonts` +
    (noText.size > 0 ? `; ${[...noText.values()].flat().length} crates with no shipped text` : ''),
);
